function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

type Rule = { pattern: RegExp; replacement: string };

function buildRules(): Rule[] {
  const sorted = [...GLOSSARY].sort((a, b) => b[0].length - a[0].length);
  return sorted.map(([en, sw]) => ({
    pattern: new RegExp(`\\b${escapeRegExp(en)}\\b`, "gi"),
    replacement: sw,
  }));
}

const RULES = buildRules();

function isAllCapsToken(match: string): boolean {
  return match.length >= 2 && match === match.toUpperCase() && /[A-Z]/.test(match);
}

/** Disease proper names the glossary must not decompose ("early blight" keeps "early"). Held aside during the pass. */
const PROTECTED = ["early blight", "late blight", "purple blotch", "powdery mildew", "downy mildew"];

/**
 * One glossary pass over English text. ALL-CAPS tokens (CAN, NPK, KES, SAM)
 * are left alone so fertilizer names and units survive the pass.
 */
export function glossaryToSwahili(text: string): string {
  let next = ` ${text} `;
  const held: string[] = [];
  for (const phrase of PROTECTED) {
    next = next.replace(new RegExp(`\\b${escapeRegExp(phrase)}\\b`, "gi"), (match) => {
      held.push(match);
      return ` \u0000${held.length - 1}\u0000 `;
    });
  }
  for (const rule of RULES) {
    next = next.replace(rule.pattern, (match) => (isAllCapsToken(match) ? match : rule.replacement));
  }
  next = next.replace(/\u0000(\d+)\u0000/g, (_, index: string) => held[Number(index)] ?? "");
  return finishSwahili(next);
}

function finishSwahili(text: string): string {
  const collapsed = text.replace(/\s+/g, " ").replace(/\s+([.,;:!?])/g, "$1").trim();
  if (!collapsed) return "";
  const lowered = collapsed.charAt(0).toLowerCase() + collapsed.slice(1);
  const sentenceCased = lowered.replace(/(^|[.!?]\s+)([a-zà-ÿ])/g, (_, prefix: string, letter: string) => `${prefix}${letter.toUpperCase()}`);
  return sentenceCased;
}

/** Repair one model sentence when it still reads as English. Proper Swahili passes through unchanged. */
export function repairSentence(locale: Locale, sentence: string): string {
  if (locale !== "sw") return sentence;
  if (!needsSwahiliRepair(sentence)) return sentence;
  return glossaryToSwahili(sentence);
}

/** Repair every model sentence in a reading. Used for observations, causes, mitigations, actions, and asks. */
export function repairSentences(locale: Locale, sentences: readonly string[]): string[] {
  if (locale !== "sw") return [...sentences];
  return sentences.map((sentence) => repairSentence(locale, sentence));
}

const SUSPECT_PLANTS: ReadonlyArray<readonly [RegExp, string]> = [
  [/\bonions?\b/gi, "Kitunguu"],
  [/\bbeets?\b/gi, "beetroot"],
  [/\bbeet\s?roots?\b/gi, "beetroot"],
  [/\bchill?ies\b/gi, "Pilipili"],
  [/\bchili\b/gi, "Pilipili"],
  [/\btomatoes\b/gi, "Nyanya"],
  [/\btomato\b/gi, "Nyanya"],
  [/\bkales?\b/gi, "Sukuma wiki"],
  [/\bcabbages?\b/gi, "Kabichi"],
  [/\bspinach\b/gi, "Mchicha"],
  [/\bbeans?\b/gi, "Maharagwe"],
];

/**
 * Repair a short suspected-problem label. Disease proper names are kept in
 * English (matching the demo suspects), while the plant and the connective
 * move to Swahili: "Purple blotch on onion" becomes "Purple blotch kwenye Kitunguu".
 */
export function repairSuspect(locale: Locale, suspect: string): string {
  if (locale !== "sw") return suspect;
  let next = suspect;
  for (const [pattern, sw] of SUSPECT_PLANTS) {
    next = next.replace(pattern, sw);
  }
  next = next.replace(/\bon\b/gi, "kwenye").replace(/\bof\b/gi, "ya");
  return next.replace(/\s+/g, " ").trim();
}
