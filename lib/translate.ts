/**
 * Glossary repair for model text. The UI chrome is fully translated in
 * `lib/copy.ts`, but Muse answers in free text and can drift into English
 * even when the farmer chose Kiswahili. Re-asking the model to translate
 * would cost a second chat call inside the 60 second Hobby limit, so a
 * `sw` result is repaired locally instead: sentences that still read as
 * English pass once through a field-term glossary. This is gist-level
 * repair for common agronomy words, not full machine translation. Proper
 * Swahili is detected first and left untouched.
 */

/** English function words. A Swahili sentence rarely holds two of these. Single letters are excluded on purpose. */
const ENGLISH_MARKERS: ReadonlySet<string> = new Set(
  `the and is are was were be been of to in on with for from that this these those you your it its as at by an or but not
   no if when while after before will can should have has had do does did they them their our his her out off over under into
   about above below more most other same only also very just any all each every some such too may might must shall would
   could because without within between during through own once many much few both until unless although though however
   therefore thus hence across along among around behind beyond plus except per`.split(/\s+/),
);

/** Swahili function words and concords. English model text holds almost none of these. */
const SWAHILI_MARKERS: ReadonlySet<string> = new Set(
  `na ya wa za la cha vya kwa ni si au ama hii hiyo huu huyu hao hizi hizo hiki hicho haya hayo hili hilo kwenye ndani nje
   kama ili lakini bado tayari sana pia tu ndiyo hapana hakuna bila kutoka hadi mpaka kati kando chini juu ndio sio basi
   tena kila baada kabla wakati pale ingawa hata halafu kisha hapa hapo humu humo hivyo hivi gani nini nani wapi lini vipi
   yote wote zote vyote moja mbili tatu nne tano kwanza pili zaidi kidogo nyingi chache kadhaa baadhi mengi mengine
   mengineyo yenye mwenye wenye lenye chenye vyenye zilizo iliyo yaliyo kilicho vilivyo ulio hao hao kiwe chawe tote`.split(/\s+/),
);

function words(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[^a-z']+/)
    .filter(Boolean);
}

export function englishScore(text: string): number {
  let score = 0;
  for (const word of words(text)) {
    if (ENGLISH_MARKERS.has(word)) score += 1;
  }
  return score;
}

export function swahiliScore(text: string): number {
  let score = 0;
  for (const word of words(text)) {
    if (SWAHILI_MARKERS.has(word)) score += 1;
  }
  return score;
}

/** True when a sentence reads as English rather than Swahili and is worth repairing. */
export function needsSwahiliRepair(text: string): boolean {
  if (text.trim().length < 8) return false;
  const en = englishScore(text);
  if (en < 2) return false;
  return en > swahiliScore(text);
}

